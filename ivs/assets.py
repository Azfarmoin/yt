"""Procedural asset catalog: original Islamic geometric patterns (no third-party artwork => no licence exposure). Every generated asset gets
a stable ID, parameters and provenance in SQLite, so assets can be reused while compositions stay different."""
from __future__ import annotations
import hashlib, json, math
from pathlib import Path
from PIL import Image, ImageDraw
from . import db as DBM

def _rgb(h): return tuple(int(h[i:i + 2], 16) for i in (1, 3, 5))

def star_cell(d: ImageDraw.ImageDraw, x0: float, y0: float, s: float, col, w: int):
    """One cell of the classic eight-pointed star (two squares at 45 degrees) with an inner octagon and corner rosettes."""
    cx, cy = x0 + s / 2, y0 + s / 2; r = s * 0.47
    for rot in (0, math.pi / 4):
        pts = [(cx + r * math.cos(rot + math.pi / 4 + k * math.pi / 2), cy + r * math.sin(rot + math.pi / 4 + k * math.pi / 2)) for k in range(4)]
        d.polygon(pts, outline=col, width=w)
    ro = r * 0.46
    d.polygon([(cx + ro * math.cos(k * math.pi / 4 + math.pi / 8), cy + ro * math.sin(k * math.pi / 4 + math.pi / 8)) for k in range(8)], outline=col, width=w)
    for kx in (0, 1):
        for ky in (0, 1):
            px, py = x0 + kx * s, y0 + ky * s; rr = s * 0.17
            d.ellipse([px - rr, py - rr, px + rr, py + rr], outline=col, width=w)

def pattern_tile(cell: int, color: str, alpha: int, width: int, height: int, period: int = 1080, line_w: int = 2) -> Image.Image:
    """Seamless horizontally when `period` is a multiple of `cell` (so the 2.5D engine can scroll it with mod())."""
    assert period % cell == 0, "cell must divide the scroll period"
    img = Image.new("RGBA", (width, height), (0, 0, 0, 0)); d = ImageDraw.Draw(img); col = _rgb(color) + (alpha,)
    for yy in range(-cell, height + cell, cell):
        for xx in range(0, width, cell): star_cell(d, xx, yy, cell, col, line_w)
    return img

def register(db, kind: str, name: str, params: dict, path: str | None = None, license_: str = "original procedural generation (CC0)", provenance: str = "generated by ivs.assets") -> str:
    aid = f"{kind}-" + hashlib.sha1(json.dumps([kind, name, params], sort_keys=True).encode()).hexdigest()[:10]
    db.conn.execute("INSERT OR REPLACE INTO assets(asset_id,kind,name,params_json,path,license,provenance,created_at) VALUES(?,?,?,?,?,?,?,?)",
                    (aid, kind, name, json.dumps(params, sort_keys=True), path, license_, provenance, DBM.now())); db.conn.commit(); return aid
